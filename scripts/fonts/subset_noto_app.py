"""Cut each Noto Sans SC slice down to the characters the app's own copy uses.

usage: python subset_noto_app.py REPO
Writes public/fonts/noto-sans-sc-app/NNN.woff2 (only slices that hold app characters) and
styles/noto-sans-sc.css: family 'Noto Sans SC'; cut-down faces cover exactly the app's characters, the full slices
cover everything else (names, news, notices from the server), with no overlap.
Re-run after adding Chinese copy (new characters still render, from the full slices).
"""
import os, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont

repo = sys.argv[1]
os.chdir(repo)
chars = set()
for base in ('components', 'app', 'lib', 'hooks'):
    for d, _, fs in os.walk(base):
        for f in fs:
            if f.endswith(('.ts', '.tsx', '.json', '.mjs')):
                text = open(os.path.join(d, f), encoding='utf-8', errors='ignore').read()
                chars.update(ord(c) for c in text if ord(c) >= 0x2000)
src_dir = 'public/fonts/noto-sans-sc'
out_dir = 'public/fonts/noto-sans-sc-app'
os.makedirs(out_dir, exist_ok=True)
for old in os.listdir(out_dir):
    os.remove(os.path.join(out_dir, old))


def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c
            continue
        out.append((start, prev)); start = prev = c
    out.append((start, prev))
    return ', '.join(f'U+{a:x}' if a == b else f'U+{a:x}-{b:x}' for a, b in out)


faces, rest, total_in, total_out, kept_chars = [], [], 0, 0, 0
for name in sorted(n for n in os.listdir(src_dir) if n.endswith('.woff2')):
    path = os.path.join(src_dir, name)
    font = TTFont(path)
    have = set(font.getBestCmap())
    want = have & chars
    if have - want:
        rest.append(f"@font-face{{font-family:'Noto Sans SC';font-style:normal;font-weight:400 700;font-display:swap;src:url('/fonts/noto-sans-sc/{name}') format('woff2');unicode-range:{ranges(have - want)}}}")
    if not want:
        continue
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(want))
    sub.subset(font)
    out = os.path.join(out_dir, name)
    font.flavor = 'woff2'
    font.save(out)
    total_in += os.path.getsize(path); total_out += os.path.getsize(out); kept_chars += len(want)
    faces.append(f"@font-face{{font-family:'Noto Sans SC';font-style:normal;font-weight:400 700;font-display:swap;src:url('/fonts/noto-sans-sc-app/{name}') format('woff2');unicode-range:{ranges(want)}}}")

HEAD = """/* Noto Sans SC (SIL OFL 1.1), self-hosted. Generated by scripts/fonts/subset_noto_app.py; do not edit by hand.
   One family, two kinds of face with no shared characters: the app's own copy comes from small cut-down files
   (public/fonts/noto-sans-sc-app), every other character (names, news, server text) from the full frequency slices
   (public/fonts/noto-sans-sc). Each character belongs to exactly one file, so a page downloads only what it shows.
   Installed copies (PingFang, HarmonyOS Sans, Noto Sans CJK) come earlier in --pa-sans. Re-run after adding Chinese copy. */
"""
with open('styles/noto-sans-sc.css', 'w', encoding='utf-8', newline='\n') as out:
    out.write(HEAD + '\n'.join(faces + rest) + '\n')
print({'chars': len(chars), 'kept': kept_chars, 'files': len(faces), 'fullFaces': len(rest), 'fullKB': total_in // 1024, 'appKB': total_out // 1024})
