// Regenerates components/maison/quant-formulas.ts. Needs mathjax-full@3.2.2, which is not an app dependency: install it
// in a scratch folder (npm i mathjax-full@3.2.2), copy this file there and run: node render-quant-formulas.mjs <repo>/components/maison/quant-formulas.ts
// TeX → self-contained SVG (glyphs as paths, fill = currentColor) for components/maison/quant-formulas.ts.
import { mathjax } from 'mathjax-full/js/mathjax.js'
import { TeX } from 'mathjax-full/js/input/tex.js'
import { SVG } from 'mathjax-full/js/output/svg.js'
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js'
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js'
import { AllPackages } from 'mathjax-full/js/input/tex/AllPackages.js'
import { writeFileSync } from 'node:fs'

const adaptor = liteAdaptor()
RegisterHTMLHandler(adaptor)
const doc = mathjax.document('', { InputJax: new TeX({ packages: AllPackages }), OutputJax: new SVG({ fontCache: 'none' }) })

const tex = {
  ofi: String.raw`\mathrm{OFI}_t=\sum_{k=1}^{K} w_k\,\Delta I_t^{(k)}`,
  micro: String.raw`P_{\text{micro}}=\frac{P_a\,Q_b+P_b\,Q_a}{Q_a+Q_b}`,
  hawkes: String.raw`\lambda(t)=\mu+\sum_{t_i<t}\alpha\,e^{-\beta\,(t-t_i)}`,
  dsr: String.raw`\mathrm{DSR}=\Phi\!\left(\frac{(\widehat{SR}-SR_0)\sqrt{T-1}}{\sqrt{1-\hat\gamma_3\,\widehat{SR}+\frac{\hat\gamma_4-1}{4}\,\widehat{SR}^{2}}}\right)`,
  es: String.raw`\mathrm{ES}_{97.5\%}=\frac{1}{0.025}\int_{0.975}^{1}\mathrm{VaR}_u(L)\,du`,
  kelly: String.raw`f^{*}=c\left(p-\frac{1-p}{b}\right),\quad 0<c<1`,
}

let out = `/* Generated by MathJax 3 (TeX → SVG, glyphs as paths, fill currentColor) on 2026-10-29. Do not edit by hand:
   change the TeX in scripts/render-quant-formulas.mjs and regenerate (see its header). The TeX source is kept for screen readers. */\n`
out += 'export const FORMULA_SVG: Record<string, { tex: string; svg: string }> = {\n'
for (const [key, source] of Object.entries(tex)) {
  const node = doc.convert(source, { display: true })
  let svg = adaptor.innerHTML(node)
  svg = svg.replace(/<svg /, '<svg aria-hidden="true" ')
  out += `  ${key}: { tex: ${JSON.stringify(source)}, svg: ${JSON.stringify(svg)} },\n`
}
out += '}\n'
writeFileSync(process.argv[2], out)
console.log('ok', Object.keys(tex).length, out.length)
