const assert = require('node:assert/strict')
const fs = require('node:fs')
const Module = require('node:module')
const ts = require('../node_modules/typescript')
const filename = require('node:path').resolve(__dirname, '../lib/session-idle.ts')
const fixture = new Module(filename)
fixture._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename)
const { needsIdleVerification, IDLE_MS } = fixture.exports
const now = Date.now()
assert.equal(needsIdleVerification(now - IDLE_MS + 1, now), false)
assert.equal(needsIdleVerification(now - IDLE_MS, now), true)
assert.equal(needsIdleVerification(now - IDLE_MS - 1, now), true)
for (const invalid of [null, undefined, '', NaN, Infinity, -1, now + 1]) assert.equal(needsIdleVerification(invalid, now), true)
assert.equal(needsIdleVerification(now, now), false)
