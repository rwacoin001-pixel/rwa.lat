const LAST = 'rwa.shareWin.last'
const today = () => new Date().toISOString().slice(0, 10)
const signed = (value: number) => `${value > 0 ? '+' : value < 0 ? '−' : ''}${Math.abs(value).toFixed(2)}%`

/** Whether this moment may be offered now: one moment per day, never one already offered or closed. */
function mayOffer(id: string): boolean {
  try {
    if (localStorage.getItem(`rwa.shareWin.done.${id}`)) return false
    const [day, last] = (localStorage.getItem(LAST) ?? '').split('|')
    return day !== today() || last === id
  } catch { return false }
}
function markOffered(id: string) { try { localStorage.setItem(LAST, `${today()}|${id}`) } catch { /* private mode: offer again next time */ } }
function markDone(id: string) { try { localStorage.setItem(`rwa.shareWin.done.${id}`, '1') } catch { /* ignore */ } }

/** The quiet line under a gain. Renders nothing for losses, guests, or once the day's offer is used. */
export function ShareWinLine({ moment }: { moment: WinMoment | null }) {
  const { locale } = useI18n()
  const c = copy[locale] ?? copy.en
  const [show, setShow] = useState(false)
  const [open, setOpen] = useState(false)
  useEffect(() => {
    if (!moment || moment.pct <= 0 || !getSessionToken() || !mayOffer(moment.id)) { setShow(false); return }
    markOffered(moment.id); setShow(true)
  }, [moment])
  if (!moment || !show) return null
  const close = () => { markDone(moment.id); setShow(false) }
  return <>
    <div className={styles.line}>
      <button type="button" className={styles.open} onClick={() => setOpen(true)}><span>{c.line}</span><ChevronRight size={16} aria-hidden="true" /></button>
      <button type="button" className={styles.dismiss} aria-label={c.dismiss} onClick={close}><X size={16} aria-hidden="true" /></button>
    </div>
    {open && <ShareWinSheet moment={moment} c={c} locale={locale} onClose={() => { setOpen(false); close() }} />}
  </>
}

function ShareWinSheet({ moment, c, locale, onClose }: { moment: WinMoment; c: Copy; locale: AppLocale; onClose: () => void }) {
  const code = useQuery('referral:v2:me', referralMe, { staleTime: 300_000 }).data?.code ?? null
  const link = inviteLinkFor(moment.path, code)
  const qrRef = useRef<HTMLDivElement>(null)
  const [image, setImage] = useState<{ blob: Blob; url: string } | null>(null)
  const [note, setNote] = useState('')
  useEffect(() => {
    let live = true, url = ''
    const qr = qrRef.current?.querySelector('canvas')
    if (!qr) return
    void drawCard(moment, c, locale, qr).then((blob) => {
      if (!live) return
      url = URL.createObjectURL(blob); setImage({ blob, url })
    }).catch(() => { if (live) setNote(c.failed) })
    return () => { live = false; if (url) URL.revokeObjectURL(url) }
  }, [moment, c, locale, link])
  const name = `a-reit-${moment.kind}-${moment.date}.png`
  const share = async () => {
    if (!image) return
    if (nativeCan('share')) { await nativeShare({ title: moment.title, url: link, image: image.blob, name }); return }
    const file = new File([image.blob], name, { type: 'image/png' })
    try {
      if (navigator.canShare?.({ files: [file] })) await navigator.share({ files: [file], url: link })
      else await navigator.share({ url: link })
    } catch { /* cancelled */ }
  }
  const save = async () => {
    if (!image) return
    if (nativeCan('save-image')) { const result = await nativeSaveImage(image.blob, name); if (result.ok) setNote(c.saved); return }
    const a = document.createElement('a'); a.href = image.url; a.download = name; a.click(); setNote(c.saved)
  }
  return <div className={styles.scrim} role="dialog" aria-modal="true" aria-label={c.sheet} onClick={(event) => { if (event.target === event.currentTarget) onClose() }}>
    <div className={styles.sheet}>
      <header><h2>{c.sheet}</h2><button type="button" aria-label={c.close} onClick={onClose}><X size={20} /></button></header>
      <div className={styles.preview}>{image ? <img src={image.url} alt={`${moment.title} ${signed(moment.pct)}`} /> : <span aria-busy="true" />}</div>
      {note && <p className={styles.note} role="status">{note}</p>}
      <div className={styles.actions}>
        <button type="button" className={styles.save} disabled={!image} onClick={() => void save()}><Download size={18} aria-hidden="true" />{c.save}</button>
        <button type="button" className={styles.share} disabled={!image} onClick={() => void share()}><Share2 size={18} aria-hidden="true" />{c.share}</button>
      </div>
      <div ref={qrRef} className={styles.qrSource} aria-hidden="true"><QRCodeCanvas value={link || 'https://a-reit.com'} size={360} marginSize={2} level="M" bgColor="#ffffff" fgColor="#0b1220" /></div>
    </div>
  </div>
}

const loadImage = (src: string) => new Promise<HTMLImageElement>((resolve, reject) => { const img = new Image(); img.onload = () => resolve(img); img.onerror = reject; img.src = src })

/** 1080×1440: the photo on top, a white panel with the figure, the date, the ledger line, the risk line and the QR. */
async function drawCard(moment: WinMoment, c: Copy, locale: AppLocale, qr: HTMLCanvasElement): Promise<Blob> {
  const W = 1080, H = 1440, canvas = document.createElement('canvas')
  canvas.width = W; canvas.height = H
  const g = canvas.getContext('2d')!
  const font = (size: number, weight = 500) => `${weight} ${size}px -apple-system, "SF Pro Display", "PingFang SC", "Noto Sans SC", "Segoe UI", sans-serif`
  g.fillStyle = '#ffffff'; g.fillRect(0, 0, W, H)
  const photo = await loadImage(moment.kind === 'quant' ? '/media/home/cards/quant-720.webp' : '/media/home/cards/predict-720.webp')
  const ph = 640, scale = Math.max(W / photo.width, ph / photo.height)
  g.drawImage(photo, (W - photo.width * scale) / 2, (ph - photo.height * scale) / 2, photo.width * scale, photo.height * scale)
  const fade = g.createLinearGradient(0, ph - 160, 0, ph); fade.addColorStop(0, 'rgba(255,255,255,0)'); fade.addColorStop(1, '#ffffff')
  g.fillStyle = fade; g.fillRect(0, ph - 160, W, 160)
  const left = 80
  g.fillStyle = '#5b6472'; g.font = font(34); g.fillText(moment.kind === 'quant' ? c.quant : c.prediction, left, 720)
  g.fillStyle = '#0b1220'; g.font = font(64, 600)
  wrap(g, moment.title, left, 800, W - left * 2, 76, 2)
  g.fillStyle = '#078a6a'; g.font = font(150, 700); g.fillText(signed(moment.pct), left - 6, 1010)
  g.fillStyle = '#5b6472'; g.font = font(32)
  g.fillText(new Intl.DateTimeFormat(locale, { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' }).format(new Date(`${moment.date}T00:00:00Z`)), left, 1070)
  g.fillStyle = '#0b1220'; g.font = font(28, 600); g.fillText(`✓ ${c.verified}`, left, 1140)
  g.fillStyle = 'rgba(11,18,32,.1)'; g.fillRect(left, 1190, W - left * 2, 2)
  g.drawImage(qr, W - left - 180, 1220, 180, 180)
  g.fillStyle = '#0b1220'; g.font = font(40, 700); g.fillText('A-REIT', left, 1270)
  g.fillStyle = '#5b6472'; g.font = font(28); g.fillText(c.scan, left, 1318)
  g.fillStyle = '#8f97a5'; g.font = font(22); wrap(g, c.risk, left, 1370, W - left * 2 - 220, 30, 2)
  return new Promise((resolve, reject) => canvas.toBlob((blob) => blob ? resolve(blob) : reject(new Error('blob')), 'image/png'))
}

function wrap(g: CanvasRenderingContext2D, text: string, x: number, y: number, width: number, lineHeight: number, maxLines: number) {
  const units = /[　-鿿]/.test(text) ? [...text] : text.split(/(\s+)/)
  let line = '', lines = 0
  for (const unit of units) {
    const next = line + unit
    if (g.measureText(next).width > width && line) {
      if (lines === maxLines - 1) { g.fillText(`${line.trimEnd()}…`, x, y + lines * lineHeight); return }
      g.fillText(line.trimEnd(), x, y + lines * lineHeight); lines += 1; line = unit.trimStart()
    } else line = next
  }
  if (line) g.fillText(line, x, y + lines * lineHeight)
}
