"""Generate support navigation from the frontend's actual route registry."""
from pathlib import Path
import re, json, sys
root = Path(__file__).resolve().parents[3]
source = (root / 'lib/routes-v2.ts').read_text(encoding='utf-8')
pages = []
for key, path, metadata in re.findall(r"(\w+): R\('([^']+)', \{([^}]+)\}\)", source):
    domain = re.search(r"domain: '([^']+)'", metadata).group(1)
    auth = re.search(r"auth: '([^']+)'", metadata).group(1)
    if domain == 'system' or key in ['notificationLink', 'shareLanding', 'maintenance']:
        continue
    pages.append({'key': key, 'path': path, 'domain': domain, 'auth': auth})
target = root / 'apps/api/src/ai/ai-pages.generated.ts'
content = '// Generated by scripts/sync-ai-page-knowledge.py; frontend routes are authoritative.\nexport const AI_PAGES = ' + json.dumps(pages, ensure_ascii=False, indent=2) + ' as const\n'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == content, 'Support navigation is stale; regenerate before release.'
else:
    target.write_text(content, encoding='utf-8', newline='\n')
print(f'AI navigation: {len(pages)} registered pages verified')
